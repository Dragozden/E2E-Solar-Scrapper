-- Step 11: independent enrichment snapshots. Existing Bronze price history untouched.
-- For an existing database: uv run python scripts/migrate_panel_specs.py
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE TABLE IF NOT EXISTS bronze.panel_spec_snapshots (
    spec_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    page_title TEXT NOT NULL DEFAULT '',
    attributes_raw JSONB NOT NULL,
    normalized_values JSONB NOT NULL,
    datasheet_urls JSONB NOT NULL DEFAULT '[]'::jsonb,
    parse_issues JSONB NOT NULL DEFAULT '[]'::jsonb,
    spec_hash TEXT NOT NULL CHECK (spec_hash ~ '^[a-f0-9]{64}$'),
    parser_version TEXT NOT NULL,
    UNIQUE (source_url, spec_hash)
);
CREATE INDEX IF NOT EXISTS idx_panel_spec_snapshots_url_time
    ON bronze.panel_spec_snapshots (source_url, fetched_at DESC, spec_id DESC);
