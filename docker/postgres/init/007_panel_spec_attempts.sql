-- Step 11.4: isolated, append-only history of individual detail-page attempts.
-- Apply to the existing DB with scripts/migrate_panel_spec_batch.py.
-- Never alters historical price snapshots, current rankings or saved spec versions.
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE TABLE IF NOT EXISTS bronze.panel_spec_attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    outcome TEXT NOT NULL CHECK (outcome IN (
        'PASS', 'INCOMPLETE', 'REVIEW', 'POWER_MISMATCH', 'SKIPPED', 'STOPPED'
    )),
    spec_id BIGINT REFERENCES bronze.panel_spec_snapshots (spec_id),
    inserted_new_version BOOLEAN NOT NULL DEFAULT FALSE,
    note TEXT NOT NULL DEFAULT '',
    runner_version TEXT NOT NULL DEFAULT 'panel-spec-batch-v1'
);
CREATE INDEX IF NOT EXISTS idx_panel_spec_attempts_url_time
    ON bronze.panel_spec_attempts (source_url, attempted_at DESC, attempt_id DESC);
