-- Step 11.5b: immutable manual approvals of model-specific STC columns from PDF.
-- Separate from HTML snapshots and historic price observations.
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE TABLE IF NOT EXISTS bronze.panel_pdf_approvals (
    approval_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url TEXT NOT NULL,
    model TEXT NOT NULL,
    power_w INTEGER NOT NULL CHECK (power_w BETWEEN 100 AND 900),
    pdf_url TEXT NOT NULL,
    pdf_sha256 TEXT NOT NULL CHECK (pdf_sha256 ~ '^[a-f0-9]{64}$'),
    review_sha256 TEXT NOT NULL CHECK (review_sha256 ~ '^[a-f0-9]{64}$'),
    pdf_page INTEGER NOT NULL CHECK (pdf_page BETWEEN 1 AND 20),
    variant_column INTEGER NOT NULL CHECK (variant_column BETWEEN 0 AND 20),
    values_stc JSONB NOT NULL CHECK (jsonb_typeof(values_stc) = 'object'),
    approved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    approval_method TEXT NOT NULL DEFAULT 'local_pdf_manual_v1'
       CHECK (approval_method = 'local_pdf_manual_v1'),
    UNIQUE (source_url, pdf_sha256, power_w, pdf_page, variant_column)
);
CREATE INDEX IF NOT EXISTS idx_panel_pdf_approvals_url_latest
    ON bronze.panel_pdf_approvals (source_url, approved_at DESC, approval_id DESC);
